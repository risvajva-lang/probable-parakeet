export function buildServerUrl(
  server: ServerProvider,
  tmdbId: number,
  type: MediaType,
  season: number = 1,
  episode: number = 1
): string {
  const isMovie = type === 'movie';
  const template = isMovie ? server.movie : server.tv;
  
  return template
    .replace(/\{tmdb_id\}/g, String(tmdbId))
    .replace(/\{season\}/g, String(season))
    .replace(/\{episode\}/g, String(episode))
    .replace(/\{s\}/g, String(season))
    .replace(/\{e\}/g, String(episode));
}
